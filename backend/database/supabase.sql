begin;
create table if not exists public.admin_users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,
  is_active integer not null default 1 check (is_active in (0,1)),
  token_version integer not null default 0,
  created_at timestamptz not null default now()
);
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  price double precision not null check (price >= 0),
  category text not null,
  image_url text,
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  is_active integer not null default 1 check (is_active in (0,1)),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  customer_phone text not null,
  customer_address text,
  total_amount double precision not null,
  status text not null default 'pending' check (status in ('pending','confirmed','cancelled','completed')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id),
  product_id bigint not null references public.products(id),
  quantity integer not null check (quantity > 0),
  price double precision not null
);
create table if not exists public.settings (key text primary key, value text not null);
alter table public.admin_users enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.settings enable row level security;
revoke all on public.admin_users, public.products, public.orders, public.order_items, public.settings from anon, authenticated;
grant all on public.admin_users, public.products, public.orders, public.order_items, public.settings to service_role;
grant usage, select on all sequences in schema public to service_role;
create or replace function public.revoke_admin_sessions(admin_id bigint) returns void
language sql set search_path = public as $$
  update public.admin_users set token_version = token_version + 1 where id = admin_id;
$$;
create or replace function public.decrement_stock(product bigint, amount integer) returns boolean
language plpgsql set search_path = public as $$
begin
  if amount <= 0 then return false; end if;
  update public.products set stock_quantity = stock_quantity - amount, updated_at = now()
  where id = product and stock_quantity >= amount;
  return found;
end;
$$;
revoke all on function public.revoke_admin_sessions(bigint) from public, anon, authenticated;
revoke all on function public.decrement_stock(bigint, integer) from public, anon, authenticated;
grant execute on function public.revoke_admin_sessions(bigint) to service_role;
grant execute on function public.decrement_stock(bigint, integer) to service_role;
commit;
